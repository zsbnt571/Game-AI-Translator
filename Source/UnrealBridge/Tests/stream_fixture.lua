local out={}
local function test(name,fn)local ok,err=pcall(fn);out[#out+1]={name=name,passed=ok,detail=not ok and tostring(err)or nil}end
test('only an observed growing control uses a complete sentence',function()
 local a=STREAM.new();local full='After thinking for a while, I wrote my reply.';a.add(full)
 local cache={[full]='想了一会儿后，我写下了回复。',['After thinking']='旧的半句话'}
 local function get(s)return cache[s]end
 assert(a.lookup('After thinking',false,get)=='旧的半句话')
 local value,source,defer=a.lookup('After thinking',true,get)
 assert(source==full and defer and value=='想了一会' and value~='旧的半句话')
 assert(a.lookup(full,true,get)==cache[full])
end)
test('ambiguous and very short prefixes never guess a sentence',function()
 local a=STREAM.new();a.add('After thinking, I left the house.');a.add('After thinking, I wrote a reply.')
 assert(a.resolve('After thinking')==nil and a.resolve('After')==nil)
 local value,full,defer=a.lookup('After thinking',true,function()return 'old fragment'end)
 assert(value==nil and full==nil and defer)
end)
test('complete short label is not expanded into another sentence',function()
 local a=STREAM.new();a.add('After thinking');a.add('After thinking I left the house.')
 assert(a.lookup('After thinking',true,function(s)return s=='After thinking'and '想过之后'or '离开'end)=='想过之后')
end)
test('UTF8 reveal never splits a character and missing cache stays original',function()
 local a=STREAM.new();local full='今日はいい天気なので、公園で休みます。';a.add(full)
 local value,source=a.lookup('今日はいい天気なので',true,function()return '天气很好，去公园休息。'end)
 assert(source==full and utf8.len(value)and #value>0)
 local absent,canonical,defer=a.lookup('今日はいい天気なので',true,function()end)
 assert(absent==nil and canonical==full and defer)
end)
test('formatted strings and invalid UTF8 are never prefix mapped',function()
 local a=STREAM.new();a.add('<b>After thinking I left.</b>');a.add('After thinking\\nI left the house.')
 a.add(string.char(255)..'invalid string here')
 assert(a.resolve('<b>After thinking')==nil)
 assert(a.resolve('After thinking')==nil)
 assert(a.resolve(string.char(255)..'invalid string')==nil)
end)
test('multiline dialogue keeps real line breaks during cached reveal',function()
 local a=STREAM.new();local full='After thinking\nI left the house.';a.add(full)
 local value,source=a.lookup('After thinking\nI left',true,function()return '思考之后，\n我离开了房子。'end)
 assert(source==full and value and utf8.len(value))
end)
test('bucket overflow disables guessing without losing exact complete sources',function()
 local a=STREAM.new();for i=1,80 do a.add('The same opening line '..i..'.')end
 assert(a.resolve('The same opening')==nil)
 assert(a.lookup('The same opening line 80.',true,function()return '完整译文'end)=='完整译文')
end)
test('CRLF runtime and LF resources use the same full sentence without growing',function()
 local a=STREAM.new();local full='They had included a map link\nwith the exact place and time.';a.add(full)
 local current=full:gsub('\n','\r\n')
 local value,canonical=a.lookup(current,false,function(s)return s==full and '其中包含了标明地点和时间的链接。'or nil end)
 assert(value=='其中包含了标明地点和时间的链接。'and canonical==full)
end)
test('line-ending variants cannot create false prefix ambiguity',function()
 local a=STREAM.new();local full='They had included a map link\nwith the exact place and time.';a.add(full);a.add(full:gsub('\n','\r\n'))
 assert(a.resolve('They had included a map link\r\nwith the exact')==full)
 local value=a.lookup('They had included a map link\r\nwith the exact',true,function(s)return s==full:gsub('\n','\r\n')and '其中包含了标明地点和时间的链接。'or nil end)
 assert(value and utf8.len(value))
end)
test('observed fragments cannot mask a complete cached sentence',function()
 local a=STREAM.new();local full='After thinking for a while, I wrote my reply.';a.add(full)
 a.add('After thinking',false)
 local value,source=a.lookup('After thinking',true,function(s)return s==full and '想了一会儿后，我写下了回复。'or '旧的半句话'end)
 assert(source==full and value=='想了一会')
end)
test('longer observed fragments do not compete with a complete sentence',function()
 local a=STREAM.new();local full='After thinking for a while, I wrote my reply.';a.add(full)
 for i=12,#full-1 do a.add(full:sub(1,i),false)end
 local value,source=a.lookup('After thinking',true,function(s)return s==full and '想了一会儿后，我写下了回复。'or nil end)
 assert(source==full and value=='想了一会')
end)

test('observations cannot overflow the complete-source prefix bucket',function()
 local a=STREAM.new()
 for i=1,90 do a.add('The same opening observed fragment '..i,false)end
 local full='The same opening now has a complete sentence.';a.add(full)
 assert(a.resolve('The same opening now')==full)
end)

return out
